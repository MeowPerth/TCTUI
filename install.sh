#!/bin/sh
# tctui installer (no packaging): copy the Python package, add a `tctui` command.
#
#   sudo ./install.sh                          # /opt/tctui + /var/lib/tctui + /usr/local/bin/tctui
#   sudo ./install.sh --data /volume1/tctui    # keep data on the big volume
#   sudo ./install.sh --migrate /volume1/docker/ffmpeg-tui   # keep old config/state/logs
#   sudo ./install.sh --uninstall [--purge]
set -eu

PREFIX=/opt/tctui
DATA=/var/lib/tctui
BIN=/usr/local/bin
MIGRATE=
UNINSTALL=0
PURGE=0

usage() {
    cat <<EOF
用法: $0 [选项]
  --prefix DIR    程序安装目录（默认 /opt/tctui）
  --data DIR      配置/状态/日志目录（默认 /var/lib/tctui）
  --bin DIR       放 tctui 命令的目录（默认 /usr/local/bin）
  --migrate DIR   把 DIR 里的 config.json/state/logs 复制过来（不覆盖已有）
  --uninstall     删除 tctui 命令（数据保留）
  --purge         配合 --uninstall，连数据一起删除
EOF
}

while [ $# -gt 0 ]; do
    case "$1" in
        --prefix) PREFIX=$2; shift 2 ;;
        --data) DATA=$2; shift 2 ;;
        --bin) BIN=$2; shift 2 ;;
        --migrate) MIGRATE=$2; shift 2 ;;
        --uninstall) UNINSTALL=1; shift ;;
        --purge) PURGE=1; shift ;;
        -h|--help) usage; exit 0 ;;
        *) echo "未知参数: $1" >&2; usage >&2; exit 2 ;;
    esac
done

if [ "$UNINSTALL" = 1 ]; then
    rm -f "$BIN/tctui"
    if [ -L /usr/bin/tctui ] && [ "$(readlink /usr/bin/tctui)" = "$BIN/tctui" ]; then
        rm -f /usr/bin/tctui
    fi
    echo "已删除 $BIN/tctui（及 /usr/bin/tctui 软链）"
    if [ "$PURGE" = 1 ]; then
        rm -rf "$DATA"
        echo "已删除数据目录 $DATA"
    else
        echo "数据保留在 $DATA（要删加 --purge）"
    fi
    exit 0
fi

SRC=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
if [ ! -d "$SRC/lib/tctui" ]; then
    echo "找不到 $SRC/lib/tctui，请在解压后的 tctui 目录里运行" >&2
    exit 2
fi

if ! command -v python3 >/dev/null 2>&1; then
    echo "找不到 python3；这个版本需要 Python 3.8+（或者改用自带运行时的版本）" >&2
    exit 2
fi
if ! python3 -c 'import sys; sys.exit(0 if sys.version_info >= (3, 8) else 1)'; then
    echo "Python 版本太旧：$(python3 -V 2>&1)，需要 3.8+" >&2
    exit 2
fi

mkdir -p "$PREFIX/lib" "$DATA" "$BIN"
rm -rf "$PREFIX/lib/tctui"
cp -a "$SRC/lib/tctui" "$PREFIX/lib/tctui"
find "$PREFIX/lib/tctui" -type d -name __pycache__ -prune -exec rm -rf {} + 2>/dev/null || true
chmod -R a+rX "$PREFIX/lib/tctui"

cat > "$BIN/tctui" <<EOF
#!/bin/sh
# generated by tctui install.sh
TCTUI_HOME="\${TCTUI_HOME:-$DATA}"
PYTHONPATH="$PREFIX/lib\${PYTHONPATH:+:\$PYTHONPATH}"
export TCTUI_HOME PYTHONPATH
exec python3 -m tctui "\$@"
EOF
chmod 755 "$BIN/tctui"

# sudo/root 的 secure_path 往往不含 /usr/local/bin，再放一个 /usr/bin 软链
if [ -d /usr/bin ] && [ -w /usr/bin ]; then
    ln -sf "$BIN/tctui" /usr/bin/tctui
fi

if [ -n "$MIGRATE" ]; then
    for item in config.json state logs; do
        if [ -e "$MIGRATE/$item" ] && [ ! -e "$DATA/$item" ]; then
            cp -a "$MIGRATE/$item" "$DATA/$item"
            echo "已迁移 $item"
        fi
    done
fi

echo "已安装: $BIN/tctui  (并软链到 /usr/bin/tctui)"
echo "  程序: $PREFIX/lib/tctui"
echo "  数据: $DATA  (config.json / state / logs)"
if ! command -v tctui >/dev/null 2>&1; then
    echo "提示: tctui 不在 PATH 里，用 $BIN/tctui，或把 $BIN 加进 PATH"
fi
echo
echo "下一步:  tctui doctor   &&   tctui"
